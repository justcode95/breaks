import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { assignment, drawFreeWinners, freePosition } from "../src/draw/draw.js";
import { fromHex, hashv, toHex, utf8 } from "../src/draw/bytes.js";
import { DrawError, Tree, leafNode, parent, sameNode, verify, type Leaf, type ProofStep } from "../src/draw/tree.js";

interface Case {
  name: string;
  leaves: { wallet: string; weight: string }[];
  root: { hash: string; sum: string };
  total: string;
  proofs: { hash: string; sum: string; sibling_is_left: boolean }[][];
  seed: string;
  free_winners: { leaf: number; start: string; weight: string; position: string }[];
  assignment_n: number;
  assignment: number[];
}

// Generated by the Rust crate (`cargo test -p draw-core`); this port must reproduce all of it.
const vectors: { cases: Case[] } = JSON.parse(
  readFileSync(join(import.meta.dirname, "..", "..", "draw-core", "vectors.json"), "utf8"),
);

const leavesOf = (c: Case): Leaf[] => c.leaves.map((l) => ({ wallet: fromHex(l.wallet), weight: BigInt(l.weight) }));
const stepsOf = (p: Case["proofs"][number]): ProofStep[] =>
  p.map((s) => ({ sibling: { hash: fromHex(s.hash), sum: BigInt(s.sum) }, siblingIsLeft: s.sibling_is_left }));

describe("the Rust test vectors", () => {
  it("has the cases the Rust side promises", () => {
    expect(vectors.cases.length).toBeGreaterThanOrEqual(7);
  });

  for (const c of vectors.cases) {
    describe(c.name, () => {
      const leaves = leavesOf(c);
      const tree = Tree.build(leaves);
      const seed = fromHex(c.seed);

      it("builds the same root", () => {
        expect(toHex(tree.root.hash)).toBe(c.root.hash);
        expect(tree.root.sum).toBe(BigInt(c.root.sum));
        expect(tree.root.sum).toBe(BigInt(c.total));
      });

      it("makes the same proofs for every leaf, and they verify", () => {
        expect(tree.leafCount).toBe(leaves.length);
        let start = 0n;
        for (const [i, leaf] of leaves.entries()) {
          const expected = stepsOf(c.proofs[i] as Case["proofs"][number]);
          const proof = tree.proof(i);
          expect(proof.map((s) => [toHex(s.sibling.hash), s.sibling.sum, s.siblingIsLeft])).toEqual(
            expected.map((s) => [toHex(s.sibling.hash), s.sibling.sum, s.siblingIsLeft]),
          );
          const v = verify(leaf, expected);
          expect(sameNode(v.root, tree.root)).toBe(true);
          expect(v.start).toBe(start);
          start += leaf.weight;
        }
      });

      it("draws the same free-spot winners", () => {
        const winners = drawFreeWinners(seed, leaves, c.free_winners.length);
        expect(
          winners.map((w) => ({
            leaf: w.leafIndex,
            start: w.start.toString(),
            weight: w.weight.toString(),
            position: w.position.toString(),
          })),
        ).toEqual(c.free_winners);
      });

      it("assigns the same cards to the same spots", () => {
        expect(assignment(seed, c.assignment_n)).toEqual(c.assignment);
      });
    });
  }
});

// ---------------------------------------------------------------- behavior (same checks as the Rust side)

const wallet = (i: number): Uint8Array => {
  const w = new Uint8Array(32);
  new DataView(w.buffer).setBigUint64(24, BigInt(i), false);
  return w;
};
const mk = (weights: bigint[]): Leaf[] => weights.map((weight, i) => ({ wallet: wallet(i + 1), weight }));
const seedOf = (n: number) => hashv(utf8("test-seed"), Uint8Array.of(n & 0xff, (n >> 8) & 0xff, (n >> 16) & 0xff));

describe("the tree", () => {
  it("a single leaf is its own root", () => {
    const [leaf] = mk([42n]) as [Leaf];
    const tree = Tree.build([leaf]);
    expect(sameNode(tree.root, leafNode(leaf))).toBe(true);
    expect(tree.proof(0)).toEqual([]);
  });

  it("every proof leads to the root and shows the leaf's range, for many sizes", () => {
    for (const n of [1, 2, 3, 4, 5, 6, 7, 8, 9, 15, 16, 17, 33, 100]) {
      const weights = Array.from({ length: n }, (_, i) => BigInt(((i * 7 + 3) % 11) + 1));
      const leaves = mk(weights);
      const tree = Tree.build(leaves);
      expect(tree.root.sum).toBe(weights.reduce((a, b) => a + b, 0n));
      let start = 0n;
      leaves.forEach((leaf, i) => {
        const v = verify(leaf, tree.proof(i));
        expect(sameNode(v.root, tree.root)).toBe(true);
        expect(v.start).toBe(start);
        start += leaf.weight;
      });
    }
  });

  it("rejects a changed weight, wallet, side, sum or path", () => {
    const leaves = mk([5n, 1n, 100n, 7n, 3n]);
    const tree = Tree.build(leaves);
    const proof = tree.proof(2);
    const leaf = leaves[2] as Leaf;
    const differs = (l: Leaf, p: ProofStep[]) => !sameNode(verify(l, p).root, tree.root);

    expect(differs({ ...leaf, weight: leaf.weight + 1n }, proof)).toBe(true);
    expect(differs({ ...leaf, wallet: wallet(99) }, proof)).toBe(true);
    expect(differs(leaf, [{ ...(proof[0] as ProofStep), siblingIsLeft: !(proof[0] as ProofStep).siblingIsLeft }, ...proof.slice(1)])).toBe(true);
    const lied = { ...(proof[0] as ProofStep), sibling: { ...(proof[0] as ProofStep).sibling, sum: (proof[0] as ProofStep).sibling.sum + 1n } };
    expect(differs(leaf, [lied, ...proof.slice(1)])).toBe(true);
    expect(differs(leaf, proof.slice(1))).toBe(true);
    expect(differs(leaf, tree.proof(3))).toBe(true);
    expect(differs(leaf, proof)).toBe(false);
  });

  it("a leaf cannot pass for an inner node", () => {
    const leaves = mk([5n, 1n]);
    const tree = Tree.build(leaves);
    expect(sameNode(leafNode({ wallet: new Uint8Array(32), weight: 6n }), tree.root)).toBe(false);
    expect(toHex(leafNode(leaves[0] as Leaf).hash)).not.toBe(toHex(parent(leafNode(leaves[0] as Leaf), leafNode(leaves[1] as Leaf)).hash));
  });

  it("rejects bad input", () => {
    const code = (f: () => unknown) => {
      try {
        f();
      } catch (e) {
        return e instanceof DrawError ? e.code : "other";
      }
      return "none";
    };
    expect(code(() => Tree.build([]))).toBe("Empty");
    const unsorted = mk([1n, 2n, 3n]);
    [unsorted[0], unsorted[2]] = [unsorted[2] as Leaf, unsorted[0] as Leaf];
    expect(code(() => Tree.build(unsorted))).toBe("NotSortedOrDuplicate");
    const dup = mk([1n, 2n, 3n]);
    dup[1] = { wallet: (dup[0] as Leaf).wallet, weight: 2n };
    expect(code(() => Tree.build(dup))).toBe("NotSortedOrDuplicate");
    expect(code(() => Tree.build(mk([1n, 0n, 3n])))).toBe("ZeroWeight");
    expect(code(() => Tree.build(mk([(1n << 64n) - 1n, 1n])))).toBe("Overflow");
    expect(code(() => Tree.build(mk([1n])).proof(1))).toBe("IndexOutOfRange");
    expect(code(() => verify(mk([1n])[0] as Leaf, Array(41).fill({ sibling: { hash: new Uint8Array(32), sum: 1n }, siblingIsLeft: false })))).toBe("ProofTooLong");
  });
});

describe("the draw", () => {
  it("skipping taken ranges maps the free weight onto exactly the free positions", () => {
    const taken: [bigint, bigint][] = [
      [2n, 3n],
      [6n, 2n],
    ];
    const seen = new Set<bigint>();
    for (let n = 0; n < 2000; n++) seen.add(freePosition(seedOf(n), 0, 10n, taken));
    expect([...seen].sort((a, b) => Number(a - b))).toEqual([0n, 1n, 5n, 8n, 9n]);
  });

  it("drawing everyone gives every wallet exactly once, even when one has almost all the weight", () => {
    const leaves = mk([1n, 1n, (1n << 64n) / 4n, 1n, 1n, 1n]);
    for (let n = 0; n < 100; n++) {
      const who = drawFreeWinners(seedOf(n), leaves, leaves.length)
        .map((w) => w.leafIndex)
        .sort((a, b) => a - b);
      expect(who).toEqual([0, 1, 2, 3, 4, 5]);
    }
  });

  it("nobody left to draw is an error", () => {
    expect(() => freePosition(seedOf(1), 0, 10n, [[0n, 10n]])).toThrow(DrawError);
    expect(() => freePosition(seedOf(1), 0, 0n, [])).toThrow(DrawError);
  });

  it("assignment is a deterministic permutation that depends on the seed", () => {
    expect(assignment(seedOf(1), 0)).toEqual([]);
    expect(assignment(seedOf(1), 1)).toEqual([0]);
    for (const n of [2, 5, 10, 50]) {
      const perm = assignment(seedOf(7), n);
      expect([...perm].sort((a, b) => a - b)).toEqual(Array.from({ length: n }, (_, i) => i));
      expect(perm).toEqual(assignment(seedOf(7), n));
    }
    expect(assignment(seedOf(1), 10)).not.toEqual(assignment(seedOf(2), 10));
  });
});
