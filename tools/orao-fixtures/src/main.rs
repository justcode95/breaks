//! Prints, as JSON, bytes and instructions produced by the real `orao-solana-vrf` 0.7.0 crate.

use anchor_lang::{prelude::Pubkey, AccountSerialize};
use orao_solana_vrf::{
    network_state_account_address, randomness_account_address,
    state::{NetworkConfiguration, NetworkState, OraoTokenFeeConfig, RandomnessAccountVersion},
    FulfillBuilder, RequestBuilder,
};

fn key(n: u8) -> Pubkey {
    Pubkey::new_from_array([n; 32])
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn state(token_fee: bool, authorities: u8) -> (NetworkState, String) {
    let config = NetworkConfiguration {
        authority: key(0x11),
        treasury: key(0x22),
        request_fee: 1_500_000_000_000 / 100_000,
        fulfillment_authorities: (0..authorities).map(|i| key(0x30 + i)).collect(),
        token_fee_config: token_fee.then(|| OraoTokenFeeConfig {
            mint: key(0x41),
            treasury: key(0x42),
            fee: 7_000_000_000,
        }),
    };
    let state = NetworkState {
        config,
        num_received: 123_456_789_012,
    };
    let mut bytes = Vec::new();
    state.try_serialize(&mut bytes).unwrap();
    (state, hex(&bytes))
}

fn config_json(s: &NetworkState) -> String {
    let c = &s.config;
    let authorities: Vec<String> = c.fulfillment_authorities.iter().map(|k| format!("\"{k}\"")).collect();
    let token = match &c.token_fee_config {
        Some(t) => format!(
            "{{ \"mint\": \"{}\", \"treasury\": \"{}\", \"fee\": \"{}\" }}",
            t.mint, t.treasury, t.fee
        ),
        None => "null".to_string(),
    };
    format!(
        "{{ \"authority\": \"{}\", \"treasury\": \"{}\", \"requestFee\": \"{}\", \"fulfillmentAuthorities\": [{}], \"tokenFee\": {}, \"numReceived\": \"{}\" }}",
        c.authority,
        c.treasury,
        c.request_fee,
        authorities.join(", "),
        token,
        s.num_received
    )
}

fn instruction_json(name: &str, ix: &anchor_lang::solana_program::instruction::Instruction) -> String {
    let accounts: Vec<String> = ix
        .accounts
        .iter()
        .map(|a| {
            format!(
                "{{ \"pubkey\": \"{}\", \"isSigner\": {}, \"isWritable\": {} }}",
                a.pubkey, a.is_signer, a.is_writable
            )
        })
        .collect();
    format!(
        "    {{ \"name\": \"{name}\", \"programId\": \"{}\", \"data\": \"{}\", \"accounts\": [{}] }}",
        ix.program_id,
        hex(&ix.data),
        accounts.join(", ")
    )
}

/// An oracle's key, from a secret of 32 copies of `n`.
fn oracle_key(n: u8) -> ed25519_dalek::Keypair {
    let secret = ed25519_dalek::SecretKey::from_bytes(&[n; 32]).unwrap();
    let public = ed25519_dalek::PublicKey::from(&secret);
    ed25519_dalek::Keypair { secret, public }
}

fn main() {
    let id = orao_solana_vrf::id();
    let payer = key(0x77);
    let seed = [9u8; 32];

    let (sol, sol_hex) = state(false, 0);
    let (full, full_hex) = state(true, 3);

    let sol_ix = RequestBuilder::new(seed)
        .into_raw_instruction(id, payer, full.config.clone())
        .unwrap();
    let token_wallet = key(0x88);
    let token_ix = RequestBuilder::new(seed)
        .pay_with_token(token_wallet)
        .into_raw_instruction(id, payer, full.config.clone())
        .unwrap();

    // How an oracle answers a request: an ed25519 instruction signing the seed, then `fulfill_v2`.
    let oracle = oracle_key(5);
    let client = key(0x66);
    let [ed25519_ix, fulfill_ix] = FulfillBuilder::new(seed).into_raw_instruction(
        id,
        payer,
        client,
        RandomnessAccountVersion::V2,
        &oracle,
    );
    let oracle_address = Pubkey::new_from_array(oracle.public.to_bytes());

    println!("{{");
    println!("  \"comment\": \"Generated by tools/orao-fixtures with the real orao-solana-vrf 0.7.0 crate. Do not edit.\",");
    println!("  \"vrfProgram\": \"{id}\",");
    println!("  \"networkStateAddress\": \"{}\",", network_state_account_address(&id));
    println!("  \"requestAddress\": \"{}\",", randomness_account_address(&id, &seed));
    println!("  \"payer\": \"{payer}\",");
    println!("  \"seed\": \"{}\",", hex(&seed));
    println!("  \"tokenWallet\": \"{token_wallet}\",");
    println!("  \"networkStates\": [");
    println!(
        "    {{ \"name\": \"sol only, no authorities\", \"data\": \"{sol_hex}\", \"decoded\": {} }},",
        config_json(&sol)
    );
    println!(
        "    {{ \"name\": \"with a token fee and three authorities\", \"data\": \"{full_hex}\", \"decoded\": {} }}",
        config_json(&full)
    );
    println!("  ],");
    println!("  \"requests\": [");
    println!("{},", instruction_json("pay the fee in SOL", &sol_ix));
    println!("{}", instruction_json("pay the fee in ORAO tokens", &token_ix));
    println!("  ],");
    println!("  \"fulfil\": {{");
    println!("    \"oracleSecret\": \"{}\",", hex(&[5u8; 32]));
    println!("    \"oracle\": \"{oracle_address}\",");
    println!("    \"client\": \"{client}\",");
    println!("    \"instructions\": [");
    println!("{},", instruction_json("ed25519 signature of the seed", &ed25519_ix));
    println!("{}", instruction_json("fulfill_v2", &fulfill_ix));
    println!("    ]");
    println!("  }}");
    println!("}}");
}
