import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { fromHex, toHex } from "../lib/draw/bytes";
import { assignment, drawFreeWinners, seedFromRandomness } from "../lib/draw/draw";
import { poolHash, sortedPool } from "../lib/draw/pool";
import { DrawError, type Leaf, treeRoot } from "../lib/draw/tree";

interface Case {
  name: string;
  leaves: { wallet: string; weight: string }[];
  root: { hash: string; sum: string };
  total: string;
  seed: string;
  free_winners: { leaf: number; start: string; weight: string; position: string }[];
  assignment_n: number;
  assignment: number[];
}

// Generated by the Rust crate (`cargo test -p draw-core`) that the program runs. This implementation, which has no code
// in common with the keeper's, must reproduce all of it.
const root = join(import.meta.dirname, "..", "..");
const vectors: { cases: Case[] } = JSON.parse(readFileSync(join(root, "draw-core", "vectors.json"), "utf8"));
const programVectors: { cases: { name: string; inputs: Record<string, string>; outputs: Record<string, string> | null }[] } = JSON.parse(
  readFileSync(join(root, "programs", "breaks", "instruction-vectors.json"), "utf8"),
);

const leavesOf = (c: Case): Leaf[] => c.leaves.map((l) => ({ wallet: fromHex(l.wallet), weight: BigInt(l.weight) }));

describe("the Rust test vectors of the draw", () => {
  it("has the cases the Rust side promises", () => {
    expect(vectors.cases.length).toBeGreaterThanOrEqual(7);
  });

  for (const c of vectors.cases) {
    describe(c.name, () => {
      const leaves = leavesOf(c);
      const seed = fromHex(c.seed);

      it("builds the same root", () => {
        const r = treeRoot(leaves);
        expect(toHex(r.hash)).toBe(c.root.hash);
        expect(r.sum).toBe(BigInt(c.root.sum));
        expect(r.sum).toBe(BigInt(c.total));
      });

      it("draws the same free-spot winners", () => {
        const winners = drawFreeWinners(seed, leaves, c.free_winners.length);
        expect(winners.map((w) => ({ leaf: w.leafIndex, start: w.start.toString(), weight: w.weight.toString(), position: w.position.toString() }))).toEqual(c.free_winners);
      });

      it("assigns the same cards to the same spots", () => {
        expect(assignment(seed, c.assignment_n)).toEqual(c.assignment);
      });
    });
  }
});

describe("the seed", () => {
  it("is derived from ORAO's 64 bytes the way the program does it", () => {
    const vector = programVectors.cases.find((c) => c.name === "breaks.draw_seed");
    expect(vector).toBeDefined();
    const answer = fromHex(vector?.inputs.answer as string);
    expect(answer).toHaveLength(64);
    expect(toHex(seedFromRandomness(answer))).toBe(vector?.outputs?.seed);
  });

  it("depends on every byte of the answer, and needs exactly 64", () => {
    const a = new Uint8Array(64).fill(5);
    const b = new Uint8Array(a);
    b[63] ^= 1;
    expect(toHex(seedFromRandomness(a))).not.toBe(toHex(seedFromRandomness(b)));
    expect(() => seedFromRandomness(new Uint8Array(63))).toThrow(/64 bytes/);
    expect(() => seedFromRandomness(new Uint8Array(65))).toThrow(/64 bytes/);
  });
});

describe("the tree", () => {
  const wallet = (n: number) => new Uint8Array(32).fill(n);

  it("refuses leaves the program would refuse", () => {
    const code = (leaves: Leaf[]) => {
      try {
        treeRoot(leaves);
      } catch (e) {
        return e instanceof DrawError ? e.code : String(e);
      }
      return "ok";
    };
    expect(code([])).toBe("Empty");
    expect(code([{ wallet: wallet(2), weight: 1n }, { wallet: wallet(1), weight: 1n }])).toBe("NotSortedOrDuplicate");
    expect(code([{ wallet: wallet(1), weight: 1n }, { wallet: wallet(1), weight: 1n }])).toBe("NotSortedOrDuplicate");
    expect(code([{ wallet: wallet(1), weight: 0n }])).toBe("ZeroWeight");
    expect(code([{ wallet: wallet(1), weight: 1n << 64n }])).toBe("Overflow");
    expect(code([{ wallet: wallet(1), weight: (1n << 64n) - 1n }, { wallet: wallet(2), weight: 1n }])).toBe("Overflow");
    expect(code([{ wallet: wallet(1), weight: 5n }])).toBe("ok");
  });

  it("does not count a carried-up node twice", () => {
    // Three leaves: the third is carried up unchanged, so the total is the plain sum.
    const r = treeRoot([1, 2, 3].map((n) => ({ wallet: wallet(n), weight: BigInt(n * 10) })));
    expect(r.sum).toBe(60n);
  });
});

describe("the pool", () => {
  const mint = (n: number) => new Uint8Array(32).fill(n);

  it("is the same whatever order the cards were pulled in", () => {
    expect(toHex(poolHash([mint(3), mint(1), mint(2)]))).toBe(toHex(poolHash([mint(1), mint(2), mint(3)])));
    expect(sortedPool([mint(3), mint(1)]).map((m) => m[0])).toEqual([1, 3]);
  });

  it("changes with any card, and refuses duplicates and short mints", () => {
    expect(toHex(poolHash([mint(1), mint(2)]))).not.toBe(toHex(poolHash([mint(1), mint(3)])));
    expect(() => poolHash([mint(1), mint(1)])).toThrow(/twice/);
    expect(() => poolHash([new Uint8Array(31)])).toThrow(/32 bytes/);
  });
});
